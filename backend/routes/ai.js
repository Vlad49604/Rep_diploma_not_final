const express = require('express');
const router = express.Router();
const Groq = require('groq-sdk');
const auth = require('../middleware/auth'); // Твій middleware авторизації

// Ініціалізація Groq (Llama 3)
const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

router.post('/explain', auth, async (req, res) => {
    try {
        const { taskText, userAnswer, correctAnswer, type } = req.body;
        
        let prompt = "";
        
        // Різні промпти залежно від типу завдання
        if (type === 'essay') {
            prompt = `Ти — дружній та професійний AI-репетитор з англійської мови на платформі Lexora. 
Твій учень щойно надіслав тобі своє есе на перевірку. ТИ МАЄШ ЗВЕРТАТИСЯ ДО НЬОГО НАПРЯМУ (на "ти").

Завдання: "${taskText}"
Есе учня: "${userAnswer}"

Твоя відповідь повинна бути структурована так:
1. Загальна оцінка (українською, звертайся безпосередньо до учня, обов'язково похвали його за старання).
2. Аналіз помилок (українською, м'яко вкажи, що саме він/вона зробив/ла не так, але самі приклади залишай англійською).
3. Поради щодо лексики (як учню зробити свій текст ще багатшим і професійнішим).
4. Кращий варіант (ОБОВ'ЯЗКОВО ТІЛЬКИ АНГЛІЙСЬКОЮ МОВОЮ). 

Важливо: Пояснення пиши українською, тепло і підбадьорливо, звертаючись виключно на "ти" (наприклад: "Ти чудово впорався, але тут варто використати..."). Фінальний "Кращий варіант" має бути виключно англійською.`;
        } else {
            prompt = `Ти — дружній AI-репетитор з англійської на платформі Lexora. 
Твій учень щойно помилився у тесті. ТИ МАЄШ ЗВЕРТАТИСЯ ДО НЬОГО НАПРЯМУ (на "ти").

Запитання: "${taskText}"
Відповідь учня: "${userAnswer}"
Правильна відповідь: "${correctAnswer}"

Поясни українською мовою, звертаючись до учня (наприклад: "Тут ти використав... а потрібно..."), у чому його помилка, та надай коротке правило. 
Приклади вживання правильної конструкції пиши англійською. 
Відповідь має бути лаконічною (3-4 речення), дружньою та підбадьорливою.`;
        }

        // Викликаємо модель Llama 3 (швидка і безкоштовна)
        // Викликаємо модель Mixtral (вона дуже стабільна і швидка)
        // Викликаємо модель Llama 3.3 (НАЙНОВІША ТА АКТУАЛЬНА)
        const chatCompletion = await groq.chat.completions.create({
            messages: [{ role: 'user', content: prompt }],
            model: 'llama-3.3-70b-versatile', 
            temperature: 0.5,
        });

        const text = chatCompletion.choices[0]?.message?.content || "Не вдалося згенерувати відповідь.";

        res.json({ success: true, explanation: text });
    } catch (error) {
        console.error('Помилка ШІ (Groq):', error);
        res.status(500).json({ success: false, message: 'Помилка генерації AI-фідбеку' });
    }
});

module.exports = router;